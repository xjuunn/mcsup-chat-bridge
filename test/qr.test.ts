function asBits(matrix: boolean[][]): string[] {
  return matrix.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""));
}

describe("qr", () => {
  it("把短文本编码为版本 1 的参考矩阵", () => {
    expect(asBits(qrMatrix("hello"))).toEqual(HELLO_MATRIX);
  });

  it("把 120 字节文本编码为版本 6 的参考矩阵", () => {
    expect(asBits(qrMatrix("a".repeat(120)))).toEqual(LONG_MATRIX);
  });

  it("选择能容纳载荷的最小版本", () => {
    expect(qrMatrix("a".repeat(17))).toHaveLength(21);
    expect(qrMatrix("a".repeat(18))).toHaveLength(25);
    expect(qrMatrix("a".repeat(271))).toHaveLength(57);
  });

  it("拒绝超出 10-L 容量的载荷", () => {
    expect(() => qrMatrix("a".repeat(272))).toThrow(/过长/);
  });

  it("渲染时保留静默区，并用上下半块合并两行", () => {
    const lines = renderQrTerminal(qrMatrix("hello")).split("\n");
    // 21 个模块行 → 11 行文本，上下各 2 行静默区
    expect(lines).toHaveLength(11 + 4);
    // 每行 4 个模块的左右静默区 → 21 + 8 个可见字符
    const widths = new Set(lines.map((line) => line.replace(/\x1b\[[0-9;]*m/g, "").length));
    expect([...widths]).toEqual([29]);
  });

  it("qrTerminal 等于矩阵渲染", () => {
    expect(qrTerminal("hello")).toBe(renderQrTerminal(qrMatrix("hello")));
  });
});